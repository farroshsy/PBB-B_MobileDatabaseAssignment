/// Button type enum to standardize appearance
enum ButtonType {
  /// Primary action button
  primary,
  
  /// Secondary action button
  secondary,
  
  /// Tertiary (text) button
  tertiary,
  
  /// Destructive action button
  destructive,
  
  /// Success action button
  success,
  
  /// Warning action button
  warning,
  
  /// Info action button
  info,
}
